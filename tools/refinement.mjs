// Focused regression checks for original sorcerers, training and shadow copies.
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { SaveSystem, sanitize } from '../src/core/save.js';
import { createSorcerer } from '../src/data/sorcerer.js';
import { CharSelectScene } from '../src/scenes/charSelect.js';
import { SparScene } from '../src/scenes/spar.js';
import { World } from '../src/game/world.js';
import { Player } from '../src/game/player.js';
import { startDomain, endDomain, updateDomain } from '../src/game/domain.js';
import { CHARACTERS } from '../src/data/characters.js';

const storage = new Map();
const backend = { getItem: (k) => storage.get(k), setItem: (k, v) => storage.set(k, v), removeItem: (k) => storage.delete(k) };
const save = new SaveSystem(backend);
const game = { save, audio: { play() {} }, toast() {}, engine: { transition: { active: false }, go() {} } };
const dom = new JSDOM('<div id="stage"></div>');
globalThis.document = dom.window.document;
const scene = new CharSelectScene(game);
scene.enter();
scene.form.elements.name.value = 'Original';
scene.form.elements.hair.value = '1';
scene.form.elements.hair.dispatchEvent(new dom.window.Event('change'));
scene.form.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(save.data.sorcerer.name, 'Original');
assert.equal(save.data.sorcerer.appearance.hair, 1);
const chosen = save.data.sorcerer.technique;
scene.exit();
const reloaded = new SaveSystem(backend); reloaded.load();
assert.equal(reloaded.data.sorcerer.technique, chosen);
assert.equal(reloaded.data.sorcerer.unlocked, 2);
assert.equal(sanitize({ sorcerer: { technique: 'invalid' } }).sorcerer, null);
const editGame = { ...game, save: reloaded };
const editor = new CharSelectScene(editGame); editor.enter();
editor.form.elements.name.value = 'Renamed';
editor.form.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(reloaded.data.sorcerer.technique, chosen, 'editing must not reroll');
editor.exit();

const world = new World(game, { arena: { x: 0, y: 0, w: 640, h: 360 }, theme: 'void' });
const player = new Player(world, { charId: chosen, save, x: 200, y: 200 });
world.player = player; world.addActor(player);
assert.equal(player.name, 'Original');
assert.equal(player.slots.length, 2);
assert.equal(player.ultimate, null);
const makeSpar = (opponentId) => ({ state: 'fight', opponentId, game, npc: { dead: true }, player, result: null });
SparScene.prototype.finish.call(makeSpar('kusakabe'), true);
assert.equal(save.data.sorcerer.trainingWins, 0);
for (let i = 0; i < 4; i++) SparScene.prototype.finish.call(makeSpar(chosen), true);
assert.equal(save.data.sorcerer.unlocked, 4);
assert.equal(save.data.sorcerer.trainingWins, 4);
assert.equal(save.data.sorcerer.mastery, 4);
const unlocked = new Player(world, { save, x: 200, y: 200 });
assert.equal(unlocked.slots.length, 4);
assert.ok(unlocked.ultimate);

save.data.sorcerer = createSorcerer('Shadow', {}, () => 0.99);
const gardenWorld = new World(game, { arena: { x: 0, y: 0, w: 640, h: 360 }, theme: 'void' });
const shadow = new Player(gardenWorld, { save, x: 200, y: 200 });
gardenWorld.player = shadow; gardenWorld.addActor(shadow);
const normal = gardenWorld.summonShikigami(shadow, 'divineDogs');
startDomain(gardenWorld, shadow, CHARACTERS.megumi.domain);
updateDomain(gardenWorld, 1);
assert.equal(gardenWorld.domain.phase, 'active');
const copies = gardenWorld.summonShikigami(shadow, 'divineDogs', { allowDuplicate: true, shadowCopy: true });
assert.ok(copies.length && copies.every((s) => s.shadowCopy));
for (let i = 0; i < 20; i++) gardenWorld.summonShikigami(shadow, 'divineDogs', { allowDuplicate: true, shadowCopy: true });
assert.ok(gardenWorld.summons.filter((s) => !s.dead).length <= 10);
endDomain(gardenWorld);
assert.ok(copies.every((s) => s.removed));
assert.ok(normal.every((s) => !s.dead), 'pre-existing summons survive');
console.log('refinement: original profile, training, persistence and shadow cleanup passed');
